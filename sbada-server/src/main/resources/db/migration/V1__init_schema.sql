-- 쓰바다 첫 스키마(테이블 12개).
-- 이 파일 이전에는 JPA ddl-auto=update 가 엔티티를 보고 테이블을 만들었다.
-- 아래 내용은 그때 Hibernate 가 만들던 DDL 과 같다(엔티티를 바꾸면 V3__... 처럼 새 파일을 추가한다. 이미 적용된 파일은 고치지 않는다).

create table app_users (
    onboarded boolean not null,
    price_max integer,
    price_min integer,
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    nickname varchar(12) not null,
    region varchar(20) not null,
    username varchar(20) not null unique,
    password_hash varchar(100) not null,
    primary key (id)
);

create table user_keywords (
    user_id bigint not null,
    keyword varchar(20),
    unique (user_id, keyword)
);

create table user_preferences (
    weight float(53) not null,
    id bigint generated by default as identity,
    updated_at timestamp(6) with time zone not null,
    user_id bigint not null,
    category enum ('ACCESSORY','APPLIANCE','BEAUTY','BOOK','DIGITAL','ETC','FASHION','FURNITURE','HOBBY','KIDS','PET','PLANT','SPORTS','TICKET') not null,
    source enum ('BEHAVIOR','ONBOARDING') not null,
    primary key (id),
    unique (user_id, category)
);

create table items (
    ai_confidence float(53) not null,
    ai_price integer not null,
    price_max integer not null,
    price_min integer not null,
    request_count integer not null,
    view_count integer not null,
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    owner_id bigint not null,
    updated_at timestamp(6) with time zone,
    version bigint not null,
    ai_provider varchar(40),
    title varchar(60) not null,
    ai_reason varchar(600),
    description varchar(1000),
    category enum ('ACCESSORY','APPLIANCE','BEAUTY','BOOK','DIGITAL','ETC','FASHION','FURNITURE','HOBBY','KIDS','PET','PLANT','SPORTS','TICKET') not null,
    item_condition enum ('FAIR','GOOD','LIKE_NEW','NEW','POOR') not null,
    status enum ('AVAILABLE','HIDDEN','TRADED') not null,
    primary key (id)
);

create table item_wish_categories (
    item_id bigint not null,
    category enum ('ACCESSORY','APPLIANCE','BEAUTY','BOOK','DIGITAL','ETC','FASHION','FURNITURE','HOBBY','KIDS','PET','PLANT','SPORTS','TICKET'),
    unique (item_id, category)
);

create table item_images (
    height integer not null,
    sort_order integer not null,
    width integer not null,
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    item_id bigint,
    size bigint not null,
    uploader_id bigint not null,
    content_type varchar(30) not null,
    stored_name varchar(60) not null unique,
    original_name varchar(120),
    primary key (id)
);

create table ai_analyses (
    confidence float(53) not null,
    final_price integer not null,
    market_median integer,
    market_samples integer not null,
    market_weight float(53) not null,
    price_max integer not null,
    price_min integer not null,
    raw_price integer not null,
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    image_id bigint not null,
    latency_ms bigint not null,
    user_id bigint not null,
    provider varchar(20),
    model varchar(60),
    suggested_title varchar(60),
    tags varchar(200),
    reason varchar(600),
    category enum ('ACCESSORY','APPLIANCE','BEAUTY','BOOK','DIGITAL','ETC','FASHION','FURNITURE','HOBBY','KIDS','PET','PLANT','SPORTS','TICKET') not null,
    item_condition enum ('FAIR','GOOD','LIKE_NEW','NEW','POOR') not null,
    primary key (id)
);

create table exchange_requests (
    chat_room_id bigint,
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    offered_item_id bigint not null,
    requester_id bigint not null,
    responded_at timestamp(6) with time zone,
    target_item_id bigint not null,
    target_owner_id bigint not null,
    close_reason varchar(120),
    message varchar(200),
    status enum ('ACCEPTED','CANCELED','REJECTED','REQUESTED') not null,
    primary key (id)
);

create table chat_rooms (
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    item_id bigint not null,
    last_message_at timestamp(6) with time zone not null,
    owner_id bigint not null,
    owner_last_read_id bigint not null,
    partner_id bigint not null,
    partner_last_read_id bigint not null,
    last_message_preview varchar(100),
    primary key (id),
    unique (item_id, partner_id)
);

create table chat_messages (
    created_at timestamp(6) with time zone not null,
    exchange_id bigint,
    id bigint generated by default as identity,
    room_id bigint not null,
    sender_id bigint,
    content varchar(1000) not null,
    msg_type enum ('PROPOSAL','SYSTEM','TEXT') not null,
    primary key (id)
);

create table notifications (
    is_read boolean not null,
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    ref_id bigint,
    user_id bigint not null,
    ref_type varchar(20),
    title varchar(80) not null,
    body varchar(300),
    noti_type enum ('CHAT_MESSAGE','EXCHANGE_ACCEPTED','EXCHANGE_CANCELED','EXCHANGE_REJECTED','EXCHANGE_REQUESTED','MATCH_SUGGESTED') not null,
    primary key (id)
);

create table device_tokens (
    id bigint generated by default as identity,
    updated_at timestamp(6) with time zone not null,
    user_id bigint not null,
    platform varchar(20),
    token varchar(300) not null unique,
    primary key (id)
);

create index idx_msg_room on chat_messages (room_id, id);
create index idx_ex_target on exchange_requests (target_item_id, status);
create index idx_ex_offered on exchange_requests (offered_item_id, status);
create index idx_ex_owner on exchange_requests (target_owner_id, id);
create index idx_items_status_price on items (status, ai_price);
create index idx_items_category on items (category);
create index idx_items_owner on items (owner_id);
create index idx_noti_user on notifications (user_id, id);
create index idx_pref_category on user_preferences (category);

