-- 2026-11-25 사용자 요청: 수락 → 바로 수락 / 추가요금 요청 → 결제(가상계좌 · 토스) → 운송장 · 배송 추적 → 정산 → 거래 후기
--  exchange_requests
--    extra_request_status : 추가요금 요청 단계 NONE · REQUESTED(받은 사람이 요청함) · AGREED(요청 보낸 사람이 수락, 결제 대기)
--                           · DECLINED(거절 → 받은 사람이 다시 선택)
--    deal_stage           : 성사 뒤 단계 NONE · SHIPPING(운송장 입력 · 배송 중) · COMPLETED(두 물건 모두 도착) · EXPIRED(7일 만료로 취소)
--    ship_deadline        : 운송장 입력 마감(성사 + 7일)
--    completed_at         : 두 물건 모두 도착한 시각
--    requester_reviewed · owner_reviewed : 거래 후기를 썼는지
--  shipments : 사람마다 운송장 하나(교환 · 보낸 사람이 같으면 고쳐 쓴다)
--  reviews   : 거래 후기(교환 · 쓴 사람마다 하나), 받은 사람 프로필에 보인다
alter table exchange_requests add column extra_request_status varchar(16) default 'NONE' not null;
alter table exchange_requests add column deal_stage varchar(16) default 'NONE' not null;
alter table exchange_requests add column ship_deadline timestamp(6) with time zone;
alter table exchange_requests add column completed_at timestamp(6) with time zone;
alter table exchange_requests add column requester_reviewed boolean default false not null;
alter table exchange_requests add column owner_reviewed boolean default false not null;

create table shipments (
    id            bigint generated by default as identity primary key,
    exchange_id   bigint not null references exchange_requests(id),
    sender_id     bigint not null references app_users(id),
    carrier_code  varchar(10) not null,
    carrier_name  varchar(30) not null,
    invoice_no    varchar(30) not null,
    status        varchar(16) not null,
    level         integer default 0 not null,
    last_detail   varchar(120),
    last_where    varchar(60),
    last_time     varchar(30),
    verified_at   timestamp(6) with time zone not null,
    delivered_at  timestamp(6) with time zone,
    checked_at    timestamp(6) with time zone not null,
    constraint uk_shipment_exchange_sender unique (exchange_id, sender_id)
);

create table reviews (
    id           bigint generated by default as identity primary key,
    exchange_id  bigint not null references exchange_requests(id),
    writer_id    bigint not null references app_users(id),
    target_id    bigint not null references app_users(id),
    rating       integer not null,
    content      varchar(300),
    created_at   timestamp(6) with time zone not null,
    constraint uk_review_exchange_writer unique (exchange_id, writer_id)
);
create index idx_review_target on reviews(target_id, id);

