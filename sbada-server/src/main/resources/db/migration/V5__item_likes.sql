-- 스바다 찜(관심목록) (2026-10-21)
-- 누가 어떤 물건을 찜했는지 한 줄씩 저장하는 새 표. 기존 표 · 데이터는 바꾸지 않는다.
-- (user_id, item_id) unique: 같은 물건을 두 번 찜해도 한 줄만 남는다.
create table item_likes (
    id bigint generated by default as identity,
    user_id bigint not null,
    item_id bigint not null,
    created_at timestamp(6) with time zone not null,
    primary key (id),
    constraint ux_item_likes_user_item unique (user_id, item_id)
);

create index idx_item_likes_user on item_likes (user_id, id);

alter table item_likes add constraint fk_item_likes_user foreign key (user_id) references app_users;
alter table item_likes add constraint fk_item_likes_item foreign key (item_id) references items;
