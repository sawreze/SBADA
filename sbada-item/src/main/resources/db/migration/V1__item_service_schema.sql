-- 물품 서비스 DB (MSA 2단계, 2026-11-25)
-- 메인 서버 DB 의 물건 · 사진 · 찜 · AI 분석 표를 그대로 옮긴 모양(V1 + V5 + V7 + V8 + V15 + V17 을 합침).
-- 다른 서비스의 표(회원 app_users)를 가리키는 외래 키는 두지 않는다(DB 는 서비스마다 따로 = Database per Service).
--  owner_id · uploader_id · user_id 는 메인 서버의 회원 번호. 목록 · 검색에 필요한 닉네임 · 동네는 sellers(읽기 모델)에 복사한다.

create table sellers (
    id bigint not null,               -- 메인 서버 회원 번호 그대로
    nickname varchar(12) not null,
    region varchar(20) not null,
    second_region varchar(20),
    updated_at timestamp(6) with time zone not null,
    primary key (id)
);

create table items (
    ai_confidence float(53) not null,
    ai_price integer not null,
    price_max integer not null,
    price_min integer not null,
    request_count integer not null,
    view_count integer not null,
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    owner_id bigint not null,
    updated_at timestamp(6) with time zone,
    version bigint not null,
    ai_provider varchar(40),
    title varchar(60) not null,
    ai_reason varchar(600),
    description varchar(1000),
    category enum ('ACCESSORY','APPLIANCE','BEAUTY','BOOK','DIGITAL','ETC','FASHION','FURNITURE','HOBBY','KIDS','PET','PLANT','SPORTS','TICKET') not null,
    item_condition enum ('FAIR','GOOD','LIKE_NEW','NEW','POOR') not null,
    status enum ('AVAILABLE','HIDDEN','TRADED','HELD') not null,
    moderation_reason varchar(200),
    farewell_message varchar(60),
    ai_summary varchar(500),
    ai_summary_provider varchar(40),
    primary key (id)
);

create table item_wish_categories (
    item_id bigint not null,
    category enum ('ACCESSORY','APPLIANCE','BEAUTY','BOOK','DIGITAL','ETC','FASHION','FURNITURE','HOBBY','KIDS','PET','PLANT','SPORTS','TICKET'),
    unique (item_id, category)
);

create table item_images (
    height integer not null,
    sort_order integer not null,
    width integer not null,
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    item_id bigint,
    size bigint not null,
    uploader_id bigint not null,
    content_type varchar(30) not null,
    stored_name varchar(60) not null unique,
    original_name varchar(120),
    primary key (id)
);

create table ai_analyses (
    confidence float(53) not null,
    final_price integer not null,
    market_median integer,
    market_samples integer not null,
    market_weight float(53) not null,
    price_max integer not null,
    price_min integer not null,
    raw_price integer not null,
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    image_id bigint not null,
    latency_ms bigint not null,
    user_id bigint not null,
    provider varchar(20),
    model varchar(60),
    suggested_title varchar(60),
    tags varchar(200),
    reason varchar(600),
    category enum ('ACCESSORY','APPLIANCE','BEAUTY','BOOK','DIGITAL','ETC','FASHION','FURNITURE','HOBBY','KIDS','PET','PLANT','SPORTS','TICKET') not null,
    item_condition enum ('FAIR','GOOD','LIKE_NEW','NEW','POOR') not null,
    new_price integer,
    primary key (id)
);

create table item_likes (
    id bigint generated by default as identity,
    user_id bigint not null,
    item_id bigint not null,
    created_at timestamp(6) with time zone not null,
    primary key (id),
    constraint ux_item_likes_user_item unique (user_id, item_id)
);

-- 허브(Kafka)로 보낼 이벤트(아웃박스) · 받은 이벤트 중복 거르기
create table outbox_events (
    id bigint generated by default as identity,
    event_id varchar(36) not null,
    topic varchar(60) not null,
    event_key varchar(40) not null,
    event_type varchar(40) not null,
    payload varchar(4000) not null,
    attempts integer not null,
    created_at timestamp(6) with time zone not null,
    sent_at timestamp(6) with time zone,
    primary key (id)
);

create table processed_events (
    event_id varchar(36) not null,
    processed_at timestamp(6) with time zone not null,
    primary key (event_id)
);

create index idx_items_status_price on items (status, ai_price);
create index idx_items_category on items (category);
create index idx_items_owner on items (owner_id);
create index idx_item_likes_user on item_likes (user_id, id);
create index idx_outbox_unsent on outbox_events (sent_at, id);

-- 같은 서비스 안의 표끼리는 외래 키를 둔다
alter table ai_analyses add constraint fk_ai_image foreign key (image_id) references item_images;
alter table item_images add constraint fk_image_item foreign key (item_id) references items;
alter table item_wish_categories add constraint fk_wish_item foreign key (item_id) references items;
alter table item_likes add constraint fk_like_item foreign key (item_id) references items;
