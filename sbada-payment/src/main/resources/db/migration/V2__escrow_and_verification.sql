-- 안전결제(에스크로) + 1원 계좌 인증 (2026-11-25)
-- 시연용 샌드박스: 실제 PG · 은행과 연결하지 않는다. 결제 · 보관 · 정산 · 환불은 이 DB 안의 숫자만 바뀐다.

-- 교환 추가 금액 안전결제: 내는 사람이 결제하면 바로 상대에게 주지 않고 '보관(HELD)'했다가
--  교환을 마치면 정산(RELEASED, 받는 사람 지갑으로) · 교환이 깨지면 환불(REFUNDED, 낸 사람에게)
--  method: CARD · KAKAOPAY · TOSSPAY · TRANSFER(외부 결제수단) 또는 WALLET(쓰바다 지갑 잔액)
--  release_after: 이 시각이 지나도 확정이 없으면 자동 정산(교환이 성사된 경우에만)
create table escrow_payments (
    id bigint generated by default as identity,
    exchange_id bigint not null,
    payer_id bigint not null,
    payee_id bigint not null,
    amount bigint not null,
    fee bigint not null,
    method varchar(20) not null,
    status varchar(20) not null,
    release_after timestamp(6) with time zone not null,
    settled_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone not null,
    primary key (id)
);
create index idx_escrow_exchange on escrow_payments (exchange_id, id);
create index idx_escrow_status on escrow_payments (status, id);

-- 1원 계좌 인증: 계좌로 1원을 보내고(시연: 실제 입금 없음) 입금자명의 숫자 4자리를 맞히면 계좌 등록
--  계좌번호는 인증 전부터 이미 암호화된 상태로만 보관(enc_account · enc_key), 숫자 4자리는 HMAC 값만 저장(code_hash)
create table account_verifications (
    id varchar(36) not null,
    user_id bigint not null,
    bank_code varchar(20) not null,
    account_masked varchar(30) not null,
    holder varchar(30) not null,
    account_hash varchar(64) not null,
    enc_account varchar(200) not null,
    enc_key varchar(700) not null,
    code_hash varchar(64) not null,
    attempts integer not null,
    expires_at timestamp(6) with time zone not null,
    verified_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone not null,
    primary key (id)
);
create index idx_verify_user on account_verifications (user_id, created_at);
