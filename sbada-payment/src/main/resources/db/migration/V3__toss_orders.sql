--  흐름: prepare(주문 만들기 READY) → 앱의 토스 결제창 → confirm(토스 승인 API)
--        카드 등: 바로 DONE → 안전결제 보관(escrow_payments) → 메인 서버가 교환을 진행
--        가상계좌: WAITING_FOR_DEPOSIT(계좌번호 발급) → 입금되면(웹훅 · 1분마다 확인) DONE → 보관 → 교환 진행
--  키는 DB 가 아니라 Git 에서 빠지는 application-local.properties 에 있다(결제_택배_키_설정.command)
create table toss_orders (
    id bigint generated by default as identity,
    order_id varchar(64) not null,
    exchange_id bigint not null,
    payer_id bigint not null,
    payee_id bigint not null,
    amount bigint not null,
    fee bigint not null,
    total bigint not null,
    method varchar(20) not null,
    status varchar(24) not null,
    payment_key varchar(200),
    va_bank varchar(30),
    va_account_number varchar(40),
    va_holder varchar(40),
    va_due_date varchar(40),
    message varchar(200),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    checked_at timestamp(6) with time zone not null,
    primary key (id),
    constraint uk_toss_order_id unique (order_id)
);
create index idx_toss_exchange on toss_orders (exchange_id, id);
create index idx_toss_status on toss_orders (status, id);
