-- 스바다 결제 서비스 DB (메인 서버 DB와 분리된 자기만의 DB)
-- 시연용: 실제 돈은 움직이지 않는다. 잔액 · 거래 내역은 이 DB 안의 숫자일 뿐이다.

-- 출금 계좌. 계좌번호 원문은 저장하지 않는다.
--  enc_account : AES-256-GCM 으로 암호화한 계좌번호(IV + 암호문, Base64)
--  enc_key     : 그 AES 키를 RSA-3072(OAEP-SHA256) 공개키로 감싼 값(Base64). 개인키가 있어야 풀린다
--  account_hash: 같은 계좌 중복 등록 확인용 HMAC-SHA256(키는 DB 밖 파일) — 되돌릴 수 없다
--  account_masked: 화면 표시용 뒷자리(****1234)
create table wallet_accounts (
    id bigint generated by default as identity,
    user_id bigint not null,
    bank_code varchar(20) not null,
    account_masked varchar(30) not null,
    holder varchar(30) not null,
    account_hash varchar(64) not null,
    enc_account varchar(200) not null,
    enc_key varchar(700) not null,
    created_at timestamp(6) with time zone not null,
    primary key (id),
    constraint ux_wallet_accounts_user_hash unique (user_id, account_hash)
);

-- 지갑 거래 내역(원장). 잔액은 마지막 줄의 balance_after.
--  tx_type: DEMO_CHARGE(시연 기본 잔액) · CHARGE(충전) · WITHDRAW(출금) · PAY(추가 요금 결제) · RECEIVE(추가 요금 받음)
--  amount : 지갑에 들어오면 +, 나가면 −. PAY 는 카드 · 간편결제로 낸 총액(−)이고 지갑 잔액은 그대로다
create table wallet_transactions (
    id bigint generated by default as identity,
    user_id bigint not null,
    tx_type varchar(20) not null,
    amount bigint not null,
    fee bigint not null,
    balance_after bigint not null,
    method varchar(20),
    account_id bigint,
    counterpart_id bigint,
    memo varchar(100),
    created_at timestamp(6) with time zone not null,
    primary key (id)
);
create index idx_wallet_tx_user on wallet_transactions (user_id, id);

-- 트랜잭셔널 아웃박스: 거래와 같은 트랜잭션에 '보낼 이벤트'를 적어 두고,
-- 별도 작업(OutboxRelay)이 메인 서버로 전달한다. 메인 서버가 꺼져 있어도 이벤트를 잃지 않는다.
create table outbox_events (
    id bigint generated by default as identity,
    event_id varchar(64) not null unique,
    event_type varchar(40) not null,
    user_id bigint not null,
    payload varchar(1000) not null,
    attempts integer not null,
    sent_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone not null,
    primary key (id)
);
create index idx_outbox_pending on outbox_events (sent_at, id);
